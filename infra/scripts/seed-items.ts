import type { ConditionRank, ItemCategory, ItemStatus, PaymentStatus, PickupStatus } from '../lambda/types';

const HOURS = 60 * 60 * 1000;
export const DAYS = 24 * HOURS;
export const now = Date.now();

// 拾得日を「実行時から何日前か」で表現し、再シードのたびに自動で最新化する
// （出品は保管期間90日満了後という前提のため、常に90日より前の日付になるようにする）
export const foundAt = (daysAgo: number): string =>
  new Date(now - daysAgo * DAYS).toISOString().slice(0, 10);

export const hashString = (value: string): number => {
  let hash = 0;
  for (const ch of value) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return hash;
};

export const generateBoxNumber = (itemId: string): number => (hashString(`box-${itemId}`) % 24) + 1;

